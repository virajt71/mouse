#[allow(dead_code)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ColorTheme {
    FollowOS,
    Light,
    Dark,
}

#[allow(dead_code)]
impl ColorTheme {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::FollowOS => "FollowOS",
            Self::Light => "Light",
            Self::Dark => "Dark",
        }
    }

    pub fn from_str(s: &str) -> Self {
        match s {
            "Light" => Self::Light,
            "Dark" => Self::Dark,
            _ => Self::FollowOS,
        }
    }
}

